def normalize(payload: dict) -> dict:
    data = json.loads(json.dumps(payload))
    for key in ("generated_at", "commit", "worktree_dirty", "dirty_paths",
                "python", "numpy"):
        data["meta"].pop(key, None)
    return data


def case_contract(payload: dict) -> dict:
    def rounded(value):
        text = str(value)
        if re.match(r"^[+\-]?\d+\.\d{4}$", text):
            return round(float(text), 2)
        return text

    return {
        case["id"]: {
            "verdict": case["verdict"],
            "reason_codes": case["reason_codes"],
            "n_items": case["board"]["n_items"],
            "n_generators": case["board"]["n_generators"],
            "metrics": [rounded(metric["value"]) for metric in case["metrics"]],
        }
        for case in payload["cases"]
    }


def banned_metric_values(payload: dict) -> set[str]:
    banned = set()
    for case in payload["cases"]:
        for metric in case["metrics"]:
            value = str(metric["value"])
            if re.match(r"^[+\-]?\d+\.\d{4}$", value):
                banned.add(value)
        if case["board"].get("votes_sha256_16"):
            banned.add(case["board"]["votes_sha256_16"])
    return banned


def find_banned_metrics(text: str, banned: set[str]) -> list[str]:
    return sorted(value for value in banned if value in text)


def find_secret_patterns(text: str) -> list[str]:
    patterns = {
        "/home/": r"/home/",
        "/Users/": r"/Users/",
        "C-drive": r"C:\\\\",
        "sk-": r"(?<![A-Za-z0-9])sk-[A-Za-z0-9]",
        "ghp_": r"(?<![A-Za-z0-9])ghp_[A-Za-z0-9]",
        "AKIA": r"AKIA[0-9A-Z]{16}",
        "private-key": r"BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY",
    }
    return sorted(name for name, pattern in patterns.items()
                  if re.search(pattern, text))


class DemoPayloadTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.payload = build_payload(generated_at=FIXED_TIME)

    def test_expected_verdicts(self) -> None:
        payload = self.payload
        self.assertEqual(payload["verification"]["status"], "MATCH")
        self.assertEqual(payload["verification"]["mismatches"], [])
        self.assertEqual(payload["summary"]["cases"], 8)
        self.assertEqual(payload["summary"]["verdicts"], {
            "READABLE": 1, "MARGINAL": 1, "UNREADABLE": 1, "UNDECIDABLE": 5,
        })
        by_id = {case["id"]: case for case in payload["cases"]}
        self.assertEqual(by_id["readable"]["verdict"], "READABLE")
        self.assertEqual(by_id["marginal"]["verdict"], "MARGINAL")
        self.assertEqual(by_id["unreadable"]["verdict"], "UNREADABLE")
        for case_id in ("two_generators", "actors_overlap", "noise",
                        "domain_mismatch", "single_generator"):
            self.assertEqual(by_id[case_id]["verdict"], "UNDECIDABLE")
        self.assertIn("domain_mismatch", by_id["domain_mismatch"]["reason_codes"])
        self.assertIn("single_generator", by_id["single_generator"]["reason_codes"])
        self.assertIn("floor_degenerate", by_id["noise"]["reason_codes"])
        self.assertIsNotNone(by_id["noise"]["chance"])

    def test_sensitivity_grid(self) -> None:
        grid = self.payload["sensitivity"]
        self.assertEqual(len(grid["rows"]), len(grid["n_items"]))
        for row in grid["rows"]:
            self.assertEqual(len(row["cells"]), len(grid["deltas"]))
            for cell in row["cells"]:
                self.assertIn(cell["verdict"],
                              {"READABLE", "MARGINAL", "UNREADABLE",
                               "UNDECIDABLE"})
        verdicts = {
            cell["verdict"] for row in grid["rows"] for cell in row["cells"]
        }
        self.assertTrue({"READABLE", "MARGINAL"} <= verdicts)
        self.assertTrue(grid["note"])

    def test_real_case(self) -> None:
        real = self.payload["real_case"]
        self.assertIsNotNone(real)
        self.assertEqual(len(real["audits"]), 2)
        by_id = {audit["id"]: audit for audit in real["audits"]}
        self.assertEqual(by_id["human"]["verdict"], "READABLE")
        self.assertEqual(by_id["llm_judge_panel"]["verdict"], "UNREADABLE")
        self.assertTrue(real["url"].startswith("https://github.com/aidless/arx/"))
        self.assertEqual(self.payload["verification"]["status"], "MATCH")
        self.assertEqual(len(self.payload["verification"]["checks"]), 26)

    def test_report_html_contract(self) -> None:
        for case in self.payload["cases"]:
            html = case["report_html"]
            self.assertIn("<!doctype html>", html.lower())
            self.assertIn(case["verdict"], html)
            self.assertNotIn("<script", html.lower())
            self.assertNotRegex(html, r"https?://")
            self.assertTrue(case["source"]["audit"].startswith("arx.audit"))

    def test_committed_artifact_matches_current_verdicts(self) -> None:
        artifact = PUBLIC / "cases.json"
        self.assertTrue(artifact.exists(), "run demo/build_static.py first")
        committed = json.loads(artifact.read_text(encoding="utf-8"))
        self.assertEqual(case_contract(committed), case_contract(self.payload))

    def test_reproducible_with_fixed_timestamp(self) -> None:
        second = build_payload(generated_at=FIXED_TIME)
        self.assertEqual(case_contract(self.payload), case_contract(second))
        self.assertEqual(normalize(self.payload), normalize(second))

    def test_write_payload_round_trip(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "cases.json"
            write_payload(path, self.payload)
            loaded = json.loads(path.read_text(encoding="utf-8"))
            self.assertEqual(loaded["summary"]["cases"], 8)


class DemoGuardTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.payload = build_payload(generated_at=FIXED_TIME)
        cls.banned = banned_metric_values(cls.payload)

    def test_ui_has_no_handwritten_metrics(self) -> None:
        for path in UI_DATA_FILES:
            text = path.read_text(encoding="utf-8")
            hits = find_banned_metrics(text, self.banned)
            self.assertEqual(hits, [], f"hardcoded metrics in {path.name}: {hits}")

    def test_metric_scanner_can_go_red(self) -> None:
        self.assertEqual(find_banned_metrics("floor 0.9210", {"0.9210"}), ["0.9210"])
        self.assertEqual(find_banned_metrics("nothing", {"0.9210"}), [])

    def test_no_secrets_or_absolute_paths(self) -> None:
        for path in PUBLIC_FILES + [
            ROOT / "demo" / "payload.py",
            ROOT / "demo" / "build_static.py",
            ROOT / "demo" / "server.py",
        ]:
            text = path.read_text(encoding="utf-8")
            hits = find_secret_patterns(text)
            self.assertEqual(hits, [], f"secret/absolute path in {path.name}: {hits}")

    def test_secret_scanner_can_go_red(self) -> None:
        self.assertEqual(find_secret_patterns("/home/alice/x"), ["/home/"])
        self.assertEqual(find_secret_patterns("sk-test"), ["sk-"])
        self.assertEqual(find_secret_patterns("safe text"), [])

    def test_static_index_contract(self) -> None:
        html = (PUBLIC / "index.html").read_text(encoding="utf-8")
        for element_id in (
            "mode-badge", "mode-note", "rerun", "summary", "case-list",
            "case-title", "case-question", "verdict", "metrics", "reasons",
            "board", "raw-toggle", "report-frame", "boundaries", "meta",
            "real-case", "real-case-cards", "real-case-link",
            "sensitivity", "sensitivity-note",
        ):
            self.assertIn(f'id="{element_id}"', html, element_id)

    def test_case_study_link(self) -> None:
        link = self.payload["case_study"]["url"]
        self.assertTrue(link.startswith("https://github.com/aidless/arx/"))

    def test_gate_table_mentions_every_reason_code(self) -> None:
        html = (PUBLIC / "index.html").read_text(encoding="utf-8")
        for code in ("actor-disjointness", "common denominator",
                     "multi-generator", "power-bounded", "floor above chance"):
            self.assertIn(code, html)


class DemoServerTest(unittest.TestCase):
    def test_api_health_cases_and_live_rerun(self) -> None:
        httpd, port = server.make_server(port=0)
        thread = threading.Thread(target=httpd.serve_forever, daemon=True)
        thread.start()
        base = f"http://127.0.0.1:{port}"
        try:
            with urllib.request.urlopen(f"{base}/api/health", timeout=5) as response:
                health = json.load(response)
            self.assertEqual(health["status"], "ok")
            self.assertEqual(health["mode"], "live")

            with urllib.request.urlopen(f"{base}/config.json", timeout=5) as response:
                config = json.load(response)
            self.assertEqual(config["mode"], "live")

            with urllib.request.urlopen(f"{base}/cases.json", timeout=60) as response:
                payload = json.load(response)
            self.assertEqual(payload["summary"]["cases"], 8)

            request = urllib.request.Request(
                f"{base}/api/run",
                data=b"{}",
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(request, timeout=60) as response:
                rerun = json.load(response)
            self.assertEqual(rerun["summary"]["cases"], 8)
            self.assertEqual(rerun["cases"][0]["id"], "readable")
        finally:
            httpd.shutdown()
            httpd.server_close()
            thread.join(timeout=5)


